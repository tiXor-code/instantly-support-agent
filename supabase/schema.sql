-- instantly-support-agent — Supabase schema
-- Run this in Supabase Studio SQL editor (or via `supabase db push`).
-- Safe to re-run: uses `create extension if not exists` and idempotent grants.
-- Tables are NOT idempotent — drop them first if iterating during development.

-- ============================================================================
-- Extensions
-- ============================================================================
create extension if not exists vector;     -- pgvector for embeddings
create extension if not exists pgcrypto;   -- gen_random_uuid()

-- ============================================================================
-- Knowledge base
-- ============================================================================

-- One row per source URL (Instantly help center article)
create table if not exists kb_docs (
  id          uuid primary key default gen_random_uuid(),
  url         text unique not null,
  title       text not null,
  category    text not null,              -- setup | deliverability | campaigns | billing | integrations
  content_md  text not null,              -- full scraped article body, markdown-ish
  scraped_at  timestamptz not null default now()
);

-- One row per chunk (paragraph-ish, ~1000 token cap with 100 token overlap)
create table if not exists kb_chunks (
  id              uuid primary key default gen_random_uuid(),
  doc_id          uuid not null references kb_docs(id) on delete cascade,
  content         text not null,
  embedding       vector(1536) not null,    -- text-embedding-3-small dimensions
  category        text not null,
  doc_url         text not null,            -- denormalized for fast retrieval response shape
  doc_title       text not null,
  section_heading text,
  chunk_index     int not null default 0,
  created_at      timestamptz not null default now()
);

-- HNSW index for fast cosine ANN over the embedding column
create index if not exists kb_chunks_embedding_idx
  on kb_chunks
  using hnsw (embedding vector_cosine_ops)
  with (m = 16, ef_construction = 64);

create index if not exists kb_chunks_category_idx on kb_chunks (category);
create index if not exists kb_chunks_doc_id_idx   on kb_chunks (doc_id);

-- ============================================================================
-- Tickets
-- ============================================================================

-- Inbound support tickets. `external_id` is a stable id from the source system
-- (or a UUID generated by the inbound webhook handler) used for idempotency.
create table if not exists tickets (
  id              uuid primary key default gen_random_uuid(),
  external_id     text unique,
  subject         text not null,
  body            text not null,
  customer_email  text not null,
  status          text not null default 'processing',
    -- processing | auto_sent | human_review | sent | rejected | error
  retry_count     int  not null default 0,
  created_at      timestamptz not null default now(),
  completed_at    timestamptz
);

-- One row per *attempt* the agent makes against a ticket.
-- A ticket can have multiple runs (retry after error, or human re-runs after edits).
create table if not exists ticket_runs (
  id                       uuid primary key default gen_random_uuid(),
  ticket_id                uuid not null references tickets(id) on delete cascade,
  classification           jsonb not null,
    -- { category, classification_confidence: 0-1, reasoning }
  top_chunks               jsonb not null,
    -- [{ chunk_id, doc_url, doc_title, score, content_snippet, category }, ...]
  draft_response           text,
  cited_docs               jsonb,
    -- [{ doc_url, doc_title }, ...]
  self_grade               jsonb,
    -- { grounded_in_cited_doc: 1-5, directly_answers_question: 1-5,
    --   tone_appropriate: 1-5, justification }
  verdict                  text not null,
    -- auto_send | human_review | cannot_answer | error
  verdict_reason           text not null,
  auto_sent                boolean not null default false,
  latency_ms               int,
  prompt_versions          jsonb,             -- { classify: 'v1', draft: 'v1', self_grade: 'v1' }
  raw_llm_outputs          jsonb,             -- preserved on parse failures for debugging
  created_at               timestamptz not null default now()
);
create index if not exists ticket_runs_ticket_id_idx on ticket_runs (ticket_id);
create index if not exists ticket_runs_verdict_idx   on ticket_runs (verdict);
create index if not exists ticket_runs_created_idx   on ticket_runs (created_at desc);

-- Audit trail for status transitions
create table if not exists ticket_status_history (
  id          uuid primary key default gen_random_uuid(),
  ticket_id   uuid not null references tickets(id) on delete cascade,
  old_status  text,
  new_status  text not null,
  changed_by  text not null,         -- n8n | webhook | human:<email>
  notes       text,
  created_at  timestamptz not null default now()
);
create index if not exists ticket_status_history_ticket_idx on ticket_status_history (ticket_id);

-- ============================================================================
-- Settings (key/value, JSONB so reviewers can hot-edit thresholds + prompts)
-- ============================================================================
create table if not exists settings (
  key         text primary key,
  value       jsonb not null,
  updated_at  timestamptz not null default now()
);

-- Seed default settings. Idempotent: re-running keeps existing values.
-- Default thresholds calibrated against the 12-ticket eval suite running on
-- text-embedding-3-small + ~34-article KB. text-embedding-3-small produces
-- relevant-match cosines in the 0.55-0.85 range on this content (not the
-- 0.85+ range we'd expect from older embedding models), so the floor sits
-- at the bottom of the relevant band, not the middle. See README §3 + §8.
insert into settings (key, value) values
  ('cosine_floor',          to_jsonb(0.60::float)),
  ('cosine_margin',         to_jsonb(0.01::float)),
  ('self_grade_floor',      to_jsonb(5::int)),
  ('classification_conf_floor', to_jsonb(0.0::float)),
    -- classification is metadata, not a hard gate; 0.0 means "always pass"
    -- can be raised later if classification reliability becomes an issue
  ('hard_floor_top1_cosine', to_jsonb(0.45::float)),
    -- below this, short-circuit to cannot_answer (no doc plausibly answers)
  ('n8n_webhook_url',       to_jsonb('https://n8n.example.com/webhook/respond-ticket'::text)),
  ('n8n_callback_secret',   to_jsonb('change-me-in-production'::text))
on conflict (key) do nothing;

-- Prompt placeholders are seeded via /api/admin/seed-prompts which reads prompts/*.md
-- at deploy time. This keeps git the source of truth while still letting
-- reviewers hot-edit in /settings.

-- ============================================================================
-- Retrieval RPC: top-k nearest chunks by cosine similarity
-- ============================================================================
create or replace function match_kb_chunks(
  query_embedding vector(1536),
  match_count int default 4
)
returns table (
  chunk_id        uuid,
  doc_url         text,
  doc_title       text,
  content         text,
  category        text,
  section_heading text,
  similarity      float
)
language sql
stable
as $$
  select
    kb_chunks.id          as chunk_id,
    kb_chunks.doc_url,
    kb_chunks.doc_title,
    kb_chunks.content,
    kb_chunks.category,
    kb_chunks.section_heading,
    1 - (kb_chunks.embedding <=> query_embedding) as similarity
  from kb_chunks
  order by kb_chunks.embedding <=> query_embedding
  limit match_count;
$$;

-- ============================================================================
-- RLS policies
-- Service role bypasses RLS automatically — used by n8n and server-side API routes.
-- Authenticated users (dashboard sessions) can read but not write directly;
-- mutations go through API routes that use the service-role client.
-- ============================================================================
alter table kb_docs                enable row level security;
alter table kb_chunks              enable row level security;
alter table tickets                enable row level security;
alter table ticket_runs            enable row level security;
alter table ticket_status_history  enable row level security;
alter table settings               enable row level security;

-- Read-only for authenticated dashboard users
do $$ begin
  if not exists (select 1 from pg_policies where policyname='auth read kb_docs') then
    create policy "auth read kb_docs"               on kb_docs               for select to authenticated using (true);
  end if;
  if not exists (select 1 from pg_policies where policyname='auth read kb_chunks') then
    create policy "auth read kb_chunks"             on kb_chunks             for select to authenticated using (true);
  end if;
  if not exists (select 1 from pg_policies where policyname='auth read tickets') then
    create policy "auth read tickets"               on tickets               for select to authenticated using (true);
  end if;
  if not exists (select 1 from pg_policies where policyname='auth read ticket_runs') then
    create policy "auth read ticket_runs"           on ticket_runs           for select to authenticated using (true);
  end if;
  if not exists (select 1 from pg_policies where policyname='auth read ticket_status_history') then
    create policy "auth read ticket_status_history" on ticket_status_history for select to authenticated using (true);
  end if;
  if not exists (select 1 from pg_policies where policyname='auth read settings') then
    create policy "auth read settings"              on settings              for select to authenticated using (true);
  end if;
end $$;

-- ============================================================================
-- Maintenance trigger: update settings.updated_at on every change
-- ============================================================================
create or replace function touch_settings_updated_at() returns trigger as $$
begin
  new.updated_at := now();
  return new;
end;
$$ language plpgsql;

drop trigger if exists settings_touch_updated_at on settings;
create trigger settings_touch_updated_at
  before update on settings
  for each row execute function touch_settings_updated_at();
